#!/usr/bin/env bash
# Refresh vendor/ from the four AltStack tool repos and record the exact commits in vendor/VENDOR.json.
# Usage: scripts/sync-vendor.sh [WORKDIR]   (clones fresh copies into WORKDIR, default: a temp dir)
# Only the headless, server-side parts are vendored: no GUI shells, no desktop launchers, no editor bundles.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="${1:-$(mktemp -d)}"
OWNER="${GP_VENDOR_OWNER:-danecohn}"
mkdir -p "$WORK"

clone() { # name
  if [ -d "$WORK/$1/.git" ]; then git -C "$WORK/$1" pull --ff-only -q; else git clone -q --depth 1 "https://github.com/$OWNER/$1" "$WORK/$1"; fi
}
for r in AmerikaEngine AmerikaRender AmerikaSprite AmerikaBox; do clone "$r"; done

copy() { # repo destdir files...
  local repo="$1" dest="$2"; shift 2
  rm -rf "$ROOT/vendor/$dest"; mkdir -p "$ROOT/vendor/$dest"
  for f in "$@"; do
    mkdir -p "$ROOT/vendor/$dest/$(dirname "$f")"
    cp -R "$WORK/$repo/$f" "$ROOT/vendor/$dest/$f"
  done
}
find_ignore() { find "$ROOT/vendor" \( -name '__pycache__' -o -name '*.uid' -o -name '.DS_Store' \) -prune -exec rm -rf {} + 2>/dev/null || true; }

copy AmerikaSprite sprite LICENSE README.md docs/sprite.md \
  src/app/js/zlib.js src/app/js/png.js src/app/js/gif.js src/app/js/color.js src/app/js/model.js src/app/js/draw.js \
  src/app/js/export.js src/app/js/aseprite.js src/app/js/session.js src/app/js/tools.js src/app/js/ai.js
copy AmerikaBox box LICENSE README.md docs/box.md src/NOTICE src/LICENSE-BeepBox.md src/beepbox.lock.json \
  src/app/beepbox_synth.min.js src/app/amerika/theory.js src/app/amerika/audio.js src/app/amerika/songtools.js \
  src/app/amerika/export.js src/app/amerika/prompt.js src/app/amerika/vendor/LICENSE-lamejs.txt
copy AmerikaEngine engine LICENSE README.md docs/engine.md src/NOTICE src/GODOT-LICENSE.txt src/addons src/templates src/icons/amerika-engine-project.svg
copy AmerikaRender render LICENSE README.md docs/render.md src/NOTICE \
  src/amerika_render/__init__.py src/amerika_render/config.py src/amerika_render/prompt.py src/amerika_render/safety.py \
  src/amerika_render/schema.py src/amerika_render/tools.py src/amerika_render/toolspecs.py
find_ignore

{
  echo '{'
  echo '  "note": "Generated by scripts/sync-vendor.sh. Do not edit by hand; changes belong upstream.",'
  echo "  \"synced\": \"$(date -u +%Y-%m-%dT%H:%M:%SZ)\","
  echo '  "sources": {'
  first=1
  for pair in "engine:AmerikaEngine" "render:AmerikaRender" "sprite:AmerikaSprite" "box:AmerikaBox"; do
    d="${pair%%:*}"; r="${pair##*:}"
    [ $first -eq 1 ] || echo ','
    first=0
    printf '    "%s": {"repo": "https://github.com/%s/%s", "commit": "%s"}' "$d" "$OWNER" "$r" "$(git -C "$WORK/$r" rev-parse HEAD)"
  done
  echo
  echo '  }'
  echo '}'
} > "$ROOT/vendor/VENDOR.json"
echo "vendored into $ROOT/vendor"
